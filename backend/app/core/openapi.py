"""Единая схема тела ошибки и помощник для описания ответов в OpenAPI.

Все ``HTTPException`` приложения отдают тело вида ``{"detail": "..."}``.
``ErrorOut`` описывает эту форму, а ``error_responses(...)`` собирает блок
``responses`` для перечисленных кодов, чтобы роутеры документировали возможные
ошибки единообразно.

Код 422 (ошибка валидации) FastAPI добавляет сам для ручек с телом, path- и
query-параметрами, поэтому отдельно его здесь не описываем.
"""

from pydantic import BaseModel, Field


class ErrorOut(BaseModel):
    """Тело ответа об ошибке."""

    detail: str = Field(
        ...,
        description="Человеко-читаемое описание ошибки",
        examples=["Описание ошибки"],
    )


# Короткие описания по кодам ответа.
_DESCRIPTIONS: dict[int, str] = {
    400: "Некорректный запрос",
    401: "Не аутентифицирован (нет или истёк токен)",
    403: "Недостаточно прав для действия",
    404: "Ресурс не найден",
    409: "Конфликт (например, логин уже занят)",
    413: "Тело запроса превышает допустимый размер",
    429: "Слишком много запросов, попробуйте позже",
    503: "Сервис временно недоступен (идёт пересчёт данных)",
}


def error_responses(*codes: int) -> dict[int, dict]:
    """Блок ``responses`` со схемой :class:`ErrorOut` для указанных кодов."""
    return {
        code: {"model": ErrorOut, "description": _DESCRIPTIONS[code]} for code in codes
    }
