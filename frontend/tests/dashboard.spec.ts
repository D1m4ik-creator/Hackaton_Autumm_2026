import { test, expect } from '@playwright/test'

test('dashboard renders the Figma snapshot without backend calls', async ({ page }) => {
  const errors: string[] = []
  const apiRequests: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  page.on('request', (request) => {
    if (request.url().includes(':8000')) apiRequests.push(request.url())
  })
  await page.goto('/dashboard')
  await expect(page.getByRole('heading', { name: 'Обзор рисков оттока' })).toBeVisible()
  await expect(page.getByText('1 284', { exact: true })).toBeVisible()
  await expect(page.getByText('14.6%', { exact: true })).toBeVisible()
  await expect(page.getByText('187 клиентов', { exact: true })).toBeVisible()
  await expect(page.getByText('€48 920', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: /^Открыть клиента/ })).toHaveCount(4)
  await page.evaluate(() => document.fonts.ready)
  await page.screenshot({ path: 'test-results/dashboard-desktop.png', fullPage: true })
  expect(errors).toEqual([])
  expect(apiRequests).toEqual([])
})

test('client exploration supports search, risk filter, details and empty state', async ({ page }) => {
  await page.goto('/dashboard')
  await page.getByRole('button', { name: 'Все →', exact: true }).click()
  const drawer = page.getByRole('dialog', { name: 'Клиенты под риском' })
  await expect(drawer.getByRole('row')).toHaveCount(7)
  await drawer.getByRole('textbox', { name: 'Поиск клиентов' }).fill('vector.ru')
  await expect(drawer.getByRole('row')).toHaveCount(2)
  await drawer.getByRole('button', { name: 'Открыть клиента ООО «Вектор»' }).click()
  await expect(page.getByText('Отключено автопродление, снизилась частота пополнений.')).toBeVisible()
  await page.getByRole('button', { name: 'К списку клиентов' }).click()
  await page.getByRole('textbox', { name: 'Поиск клиентов' }).fill('нет-такого-клиента')
  await expect(page.getByText('Клиенты не найдены')).toBeVisible()
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: /ВЫСОКИЙ РИСК: 187/ }).click()
  await expect(page.getByRole('dialog').getByRole('row')).toHaveCount(4)
  await expect(page.getByRole('dialog').getByText('Мария Седова')).toHaveCount(0)
})

test('chart period changes data while preserving the summary', async ({ page }) => {
  await page.goto('/dashboard')
  await expect(page.locator('.risk-trend__bar')).toHaveCount(8)
  await page.getByRole('combobox', { name: 'Период графика' }).click()
  await page.getByText('30 дней', { exact: true }).click()
  await expect(page.locator('.risk-trend__bar')).toHaveCount(30)
  await expect(page.getByText('1 284', { exact: true })).toBeVisible()
  await page.getByRole('combobox', { name: 'Период графика' }).click()
  await page.getByText('7 дней', { exact: true }).click()
  await expect(page.locator('.risk-trend__bar')).toHaveCount(8)
})

